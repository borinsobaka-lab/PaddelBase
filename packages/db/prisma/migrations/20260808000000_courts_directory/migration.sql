-- Справочник кортов переезжает из сида в миграцию.
--
-- Причина: сид на выкатке не запускается и запускаться не должен — он кладёт
-- тестовых игроков. Без справочника выпадающий список кортов пуст, а значит
-- матч нельзя создать вообще: поле обязательное. Данные, без которых
-- приложение не работает, обязаны приезжать вместе со схемой.
--
-- ВРЕМЕННЫЕ ДАННЫЕ. Названия — по районам Тбилиси и городам Грузии, а не
-- реальные названия клубов: выдумывать их нельзя, они попадут в интерфейс и
-- будут выглядеть достоверно. Координаты не заполнены по той же причине.

-- Уникальность пары «название + город»: два одинаковых клуба в одном городе —
-- это ошибка данных. Заодно делает вставку ниже идемпотентной.
CREATE UNIQUE INDEX "courts_name_city_key" ON "app"."courts"("name", "city");

