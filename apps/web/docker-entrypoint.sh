#!/bin/sh
set -e

# Миграции применяются при старте контейнера, а не отдельной командой выкатки.
#
# Причина не в удобстве. Pre-deployment command в Coolify выполняется внутри
# уже работающего контейнера, и на первой выкатке его просто нет: в логе
# появляется «No running containers found. Skipping», выкатка считается
# успешной, а приложение поднимается к базе без единой таблицы. Отказ, который
# ничего о себе не сообщает, — худший вид отказа.
#
# Здесь же всё наоборот: не прошла миграция — контейнер не стартовал, Coolify
# оставил работать прежнюю версию и показал ошибку.
#
# Повторный запуск безопасен: `migrate deploy` применяет только неприменённое,
# а на время работы берёт advisory-блокировку в самой базе, поэтому несколько
# экземпляров, стартующих одновременно, не столкнутся.

echo "==> Применяю миграции"
prisma migrate deploy --schema packages/db/prisma/schema.prisma

echo "==> Запускаю приложение"
exec node apps/web/server.js
