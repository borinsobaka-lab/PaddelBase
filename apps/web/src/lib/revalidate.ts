import { revalidatePath } from 'next/cache';

/**
 * Сброс кеша списочных экранов.
 *
 * Один матч виден сразу на трёх экранах: в «моих матчах» на главной, в ленте
 * свободных мест и в списке игр. Действие, которое меняет матч, обязано
 * сбросить их все — иначе игрок откликается на заявку, возвращается на
 * главную и видит её в прежнем виде.
 *
 * Раньше это сходило с рук: клиентский кеш роутера был выключен, и каждый
 * переход всё равно шёл на сервер. Теперь переходы берутся из кеша, и
 * пропущенный сброс стал бы видимым багом.
 *
 * Побочный эффект намеренный: вызов `revalidatePath` в серверном действии
 * инвалидирует клиентский кеш роутера целиком. Именно поэтому действие,
 * которое ничего не revalidate'ит, оставляет игрока со старым экраном.
 */
export function revalidateFeeds(): void {
  revalidatePath('/home');
  revalidatePath('/games');
}

/** Списки плюс уведомления: действие создало уведомление кому-то из игроков. */
export function revalidateFeedsAndNotifications(): void {
  revalidateFeeds();
  revalidatePath('/notifications');
}
